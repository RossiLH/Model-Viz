def comparison():
    """图 2：全注意力 vs 因子化对比。"""
    print("""
================================================================================
  图 2：计算量对比 —— 全注意力（稠密网） vs 因子化（分解网）
================================================================================

  场景：F=4 帧, N=256 patch/帧, D=128

──────────────────────────────────────────────────────────────────────────────
  全注意力：一张稠密大网
──────────────────────────────────────────────────────────────────────────────

       帧1        帧2        帧3        帧4
      ┌──┐      ┌──┐      ┌──┐      ┌──┐
      │██│ ◄──► │██│ ◄──► │██│ ◄──► │██│       每个 token 都和
      │██│ ◄──► │██│ ◄──► │██│ ◄──► │██│       其他 1023 个 token
      └──┘      └──┘      └──┘      └──┘       算注意力分数
       ▲          ▲          ▲          ▲
       └──────────┴──────────┴──────────┘
                  全部两两互联
       token 数 = 4 · 256 = 1024
       注意力矩阵 = 1024² = 1,048,576 元素
       FLOPs ∝ F²·N²·D = 4²·256²·128 ≈ 134 G


──────────────────────────────────────────────────────────────────────────────
  因子化：分解为两张小网（空间 + 时间）
──────────────────────────────────────────────────────────────────────────────

  ① 空间 pass（帧内小网）         ② 时间 pass（跨帧细线）

       帧1        帧2                位置(0,0)  位置(0,1)  ... 位置(15,15)
      ┌──┐      ┌──┐                  │          │             │
      │██│      │██│                  ●          ●             ●   ← 帧1
      │██│      │██│ (各自内部)       │          │             │
      └──┘      └──┘                  ●          ●             ●   ← 帧2
       帧3        帧4                 │          │             │
      ┌──┐      ┌──┐                  ●          ●             ●   ← 帧3
      │██│      │██│                  │          │             │
      │██│      │██│                  ●          ●             ●   ← 帧4
      └──┘      └──┘                  ↑          ↑             ↑
                                  每个位置跨 4 帧做 4×4 注意力
       每帧内部 256×256               共 256 条这样的"时间线"
       全连接                         共享同一份 q/k/v/o 权重

  总计算：
    空间 = F · N² · D = 4 · 256² · 128 ≈ 33.5 G
    时间 = N · F² · D = 256 · 4² · 128 ≈ 0.5 G
    合计 ≈ 34 G       （vs 全注意力 134 G）


──────────────────────────────────────────────────────────────────────────────
  数字一目了然
──────────────────────────────────────────────────────────────────────────────

                    全注意力       因子化         比值
  token 对数        1,048,576      262,144+65,536   ≈ 3.2x
  FLOPs (相对)      134 G          34 G              ≈ 3.9x
  参数量            W              W（共享，零新增）  1.0x
  通用公式          F²·N²          F·N² + N·F²       FN/(N+F)

  关键：F 越大，因子化收益越大
    F=4   → 3.9x
    F=16  → 15.1x
    F=64  → 60.2x


──────────────────────────────────────────────────────────────────────────────
  信息可达性：单层 vs 多层
──────────────────────────────────────────────────────────────────────────────

  单层因子化：
    ★ → 空间聚合 → 时间分发    跨帧跨位置（如帧1左上 → 帧4右下）不可达

  L 层堆叠：
    Layer1: 帧1左上 ─聚合→ 帧1综合 ─跨帧→ 帧2综合 ─聚合→ 帧2右下
    Layer2: 帧2右下 ─聚合→ 帧2综合 ─跨帧→ 帧3综合 ─聚合→ 帧3右下
    ...
    每层"接力"一帧，L ≥ F 后整个时空感受野全覆盖
""")


