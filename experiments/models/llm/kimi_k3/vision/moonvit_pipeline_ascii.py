"""MoonViT-V2 图像/视频压缩管线 ASCII 可视化（提纲挈领）。"""


def image_pipeline():
    """图 1：图像压缩管线 —— 一张 384x384 图像如何变成 169 个 token。"""
    print("""
================================================================================
  图 1：MoonViT-V2 如何压缩一张图像？（以 384x384 为例）
================================================================================

   原始图像             Patch 切分           ViT 处理          Pixel Shuffle      LLM
   384 x 384            27 x 27 网格          729 token          2x2 折叠            169 token
                                                                                       │
                                                                                       ▼
 ┌──────────────┐    ┌──┬──┬──┬──┬──┐    ┌─────────────┐    ┌──┬──┬──┐         ┌─────────────┐
 │              │    │▓▓│▓▓│▓▓│..│▓▓│    │ 27 层 ViT   │    │▓▓▓│▓▓▓│..│         │             │
 │              │    ├──┼──┼──┼──┼──┤    │             │    ├──┼──┼──┤         │  语言模型    │
 │   [照片]     │ →  │▓▓│▓▓│▓▓│..│▓▓│ →  │ 注意力+FFN  │ →  │▓▓▓│▓▓▓│..│    →   │  （文本生成）│
 │   384x384    │    ├──┼──┼──┼──┼──┤    │ 双向注意力  │    ├──┼──┼──┤         │             │
 │              │    │..│..│..│..│..│    │ 无位置编码  │    │..│..│..│         │ 169 个视觉   │
 │              │    ├──┼──┼──┼──┼──┤    │ 只感知内容  │    └──┴──┴──┘         │ token 嵌入   │
 │              │    │▓▓│▓▓│▓▓│..│▓▓│    │ 和相对关系  │     13 x 13          │ 文本序列     │
 └──────────────┘    └──┴──┴──┴──┴──┘    └─────────────┘                      └─────────────┘
                          │                                  │
                     每 patch 14x14                     每 4 个 token
                     共 27 x 27                        折叠成 1 个
                     = 729 token                       通道 x4
                                                       (token 数 /4)

────────────────────────────────────────────────────────────────────────────────
  数字一目了然
────────────────────────────────────────────────────────────────────────────────

   阶段              空间尺寸         token 数       通道数      说明
   ─────────────────────────────────────────────────────────────────────────
   输入图像           384 x 384           -             3       原始像素
   Patchify           27 x 27            729           1152     14x14/patch
   ViT 27 层          27 x 27            729           1152     无位置编码
   Pixel Shuffle 2x2  13 x 13            169           4608     token /4, 通道 x4
   → 送入 LLM                              169          4608     ~4x 压缩

   压缩比：729 → 169 ≈ 4.3x（token 数）；384 → 169 ≈ 2.3x（线性尺寸）
   关键：token 数从 729 降到 169，让图像能进入 1M 上下文预算


────────────────────────────────────────────────────────────────────────────────
  为什么这样压缩是"无损"的？
────────────────────────────────────────────────────────────────────────────────

   Pixel Shuffle 前：4 个相邻 token        Pixel Shuffle 后：1 个宽 token
   ┌──┬──┐                                ┌─────────┐
   │A │B │  每个 token 通道 = 1152         │ A|B|C|D │  通道 = 1152 x 4 = 4608
   ├──┼──┤         →                      │         │
   │C │D │                                │ (拼接)  │
   └──┴──┘                                └─────────┘

   → 空间 2x2 邻域 → 通道维 4x 展开
   → 不做任何下采样/池化/卷积 stride
   → 是"空间→通道"的纯重排（pixel_unshuffle 可完全还原）
   → 与 PixelUnshuffle (PyTorch) 互为逆运算
""")


def video_pipeline():
    """图 2：视频压缩管线 —— 8 帧 384x384 视频如何变成 676 个 token。"""
    print("""
================================================================================
  图 2：MoonViT-V2 如何压缩一段视频？（以 8 帧 384x384 为例）
================================================================================

   原始视频             Patch 切分           ViT 处理          Temporal Pack    Pixel Shuffle   LLM
   8 帧 384x384         每帧 27x27           729 token/帧       2 帧合一          2x2 折叠         676 token
                                                                                                     │
                                                                                                     ▼
 ┌──┬──┬──┬──┐    ┌──┬──┬──┬──┐    ┌─────────────┐    ┌──┬──┐         ┌──┬──┐                  ┌─────────────┐
 │F1│F2│F3│..│    │▓▓│▓▓│▓▓│..│    │ 27 层 ViT   │    │▓▓│▓▓│         │▓▓│▓▓│                  │             │
 ├──┼──┼──┼──┤    ├──┼──┼──┼──┤    │             │    ├──┼──┤         ├──┼──┤                  │  语言模型    │
 │F5│F6│F7│F8│    │▓▓│▓▓│▓▓│..│    │ 因子化注意力 │ →  │▓▓│▓▓│    →   │▓▓│▓▓│             →   │  （文本生成）│
 └──┴──┴──┴──┘    ├──┼──┼──┼──┤    │ (空间+时间) │    ├──┼──┤         ├──┼──┤                  │             │
                  │▓▓│▓▓│▓▓│..│    │ 无位置编码  │    │▓▓│▓▓│         │▓▓│▓▓│                  │ 676 个视觉   │
                  ├──┼──┼──┼──┤    │ 只感知内容  │    └──┴──┘         └──┴──┘                  │ token 嵌入   │
                  │▓▓│▓▓│▓▓│..│    │ 和相对关系  │     4 x 169         4 x 169                │ 文本序列     │
                  └──┴──┴──┴──┘    └─────────────┘    = 676           = 676                   └─────────────┘
                       │                  │
                  每帧 27x27            8 帧 → 4 帧
                  = 729 token/帧        (每 2 帧平均)
                  8 帧总 = 5832         token 数 /2

────────────────────────────────────────────────────────────────────────────────
  数字一目了然
────────────────────────────────────────────────────────────────────────────────

   阶段              帧数    空间尺寸    总 token 数    通道数      说明
   ─────────────────────────────────────────────────────────────────────────
   输入视频            8      384x384         -            3       原始像素
   Patchify            8      27x27         5832         1152     14x14/patch
   ViT 27 层           8      27x27         5832         1152     因子化注意力
   Temporal Pack 2x    4      27x27         2916         1152     每 2 帧平均 → token /2
   Pixel Shuffle 2x2   4      13x13          676         4608     token /4, 通道 x4
   → 送入 LLM          4                      676         4608     ~8.6x 压缩

   压缩比：5832 → 676 ≈ 8.6x（token 数）
   关键：temporal pack 和 pixel shuffle 叠加，压缩比 = 2 x 4 = 8x


────────────────────────────────────────────────────────────────────────────────
  为什么视频要"先时序压缩、再空间压缩"？
────────────────────────────────────────────────────────────────────────────────

   时序相邻帧内容高度冗余（短视频 < 10s）：
     帧 t     ●──●──●──●      帧 t+1   ●──●──●──●
              │  │  │  │               │  │  │  │
              ▼  ▼  ▼  ▼               ▼  ▼  ▼  ▼
             几乎相同的场景，只是微小运动

   → Temporal Pack 把 2 帧平均成 1 帧，去掉时序冗余
   → Pixel Shuffle 把 4 空间 token 折叠成 1 宽 token，去掉空间冗余
   → 两种压缩"正交"，可叠加使用
   → 最终 8 帧视频从 5832 token 压到 676 token，LLM 能处理


────────────────────────────────────────────────────────────────────────────────
  与图像管线的对比（一眼看出差异）
────────────────────────────────────────────────────────────────────────────────

                    图像管线                    视频管线
                    ────────                    ────────
   输入             1 x 384x384                 8 x 384x384
   Patchify         729 token                   5832 token (8x)
   ViT              双向注意力                  因子化注意力（空间+时间）
   Temporal Pack    [跳过]                      5832 → 2916 (2x)
   Pixel Shuffle    729 → 169 (4.3x)            2916 → 676 (4.3x)
   最终 token       169                         676
   压缩比           4.3x                        8.6x

   关键洞察：视频 = 图像管线 + Temporal Pack（多一步时序压缩）
            ViT 内部用因子化注意力替代双向注意力，处理多帧
            其他所有步骤（patchify、pixel shuffle）与图像完全一致
""")


if __name__ == "__main__":
    image_pipeline()
    video_pipeline()
