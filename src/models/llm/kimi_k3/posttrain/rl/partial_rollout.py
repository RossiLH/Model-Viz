"""Partial rollout (paper section 4.1.2).

Long-horizon agentic tasks have a brutal latency tail: a single trajectory may
span thousands of tool calls and millions of tokens, so waiting for every rollout
to terminate leaves the trainer idle behind one straggler.

K3 extends the partial-rollout scheme of its synchronous RL framework.  For each
of ``N`` prompts, ``K`` completions are sampled, giving ``N * K`` active
trajectories.  Rather than waiting for all of them, the generation phase *pauses*
as soon as a fraction ``lambda`` of trajectories completes, and policy
optimisation proceeds without execution stragglers.  Paused rollouts are enqueued
and prioritised for resumption at the start of the next iteration, powered by the
resumable sandbox infrastructure.  Once all ``K`` responses for a prompt are
complete they are immediately dispatched for policy optimisation.

The cost is staleness: an individual long-horizon trajectory naturally spans
several iterations, so its tokens were generated by an older policy.  This is an
extreme off-policy regime, and it is handled by a **per-token regularizer** that
constrains policy updates to a localised neighbourhood, rather than by waiting.
"""

from __future__ import annotations

import heapq
from dataclasses import dataclass, field

import torch
from torch import Tensor

__all__ = [
    "Trajectory",
    "PartialRolloutScheduler",
    "staleness_regularizer",
    "clipped_policy_ratio",
]


@dataclass
class Trajectory:
    """一条轨迹：prompt + 样本 + token 序列 + 迭代记录。"""
    prompt_id: int
    sample_id: int
    tokens: list[int] = field(default_factory=list)
    #: Iteration at which each token was generated, for staleness accounting.
    token_iteration: list[int] = field(default_factory=list)
    done: bool = False
    #: Sandbox handle, preserved across pauses.
    sandbox: object = None
    paused_at_iteration: int | None = None
    steps: int = 0

    @property
    def key(self) -> tuple[int, int]:
        return (self.prompt_id, self.sample_id)

    def staleness(self, current_iteration: int) -> list[int]:
        """计算每个 token 的陈旧度（当前迭代 - 生成迭代）。"""
        return [current_iteration - it for it in self.token_iteration]


@dataclass
class PartialRolloutScheduler:
    """运行生成阶段并决定何时截断。"""

    n_prompts: int
    k_samples: int
    lam: float = 0.5
    iteration: int = 0
    active: dict[tuple[int, int], Trajectory] = field(default_factory=dict)
    #: Min-heap of paused trajectories, prioritised for resumption.
    paused: list[tuple[int, tuple[int, int]]] = field(default_factory=list)
    completed: list[Trajectory] = field(default_factory=list)

    def __post_init__(self) -> None:
        if not 0.0 < self.lam < 1.0:
            raise ValueError("lambda must lie strictly between 0 and 1")

    @property
    def target_active(self) -> int:
        return self.n_prompts * self.k_samples

    def start_iteration(self, new_prompts: list[int] | None = None) -> list[Trajectory]:
        """优先恢复暂停的轨迹，然后用新 prompt 填充。

        优先恢复是为了防止长轨迹被短 prompt 流饿死。
        """
        self.iteration += 1
        batch: list[Trajectory] = []
        while self.paused and len(batch) < self.target_active:
            _, key = heapq.heappop(self.paused)
            traj = self.active.get(key)
            if traj is None:
                continue
            traj.paused_at_iteration = None
            batch.append(traj)

        for pid in new_prompts or []:
            for s in range(self.k_samples):
                if len(batch) >= self.target_active:
                    break
                traj = Trajectory(prompt_id=pid, sample_id=s)
                self.active[traj.key] = traj
                batch.append(traj)
        return batch

    def should_pause(self) -> bool:
        """当 lambda 比例的活跃轨迹完成时暂停。"""
        if not self.active:
            return False
        done = sum(1 for t in self.active.values() if t.done)
        return done >= self.lam * len(self.active)

    def pause_remaining(self) -> list[Trajectory]:
        """将仍在运行的轨迹入队，其沙箱状态被保留。"""
        paused = []
        for traj in self.active.values():
            if not traj.done and traj.paused_at_iteration is None:
                traj.paused_at_iteration = self.iteration
                heapq.heappush(self.paused, (traj.paused_at_iteration, traj.key))
                paused.append(traj)
        return paused

    def harvest(self) -> list[list[Trajectory]]:
        """返回 K 个样本全部完成的 prompt 组，用于策略优化。"""
        groups: dict[int, list[Trajectory]] = {}
        for traj in self.active.values():
            groups.setdefault(traj.prompt_id, []).append(traj)

        ready = []
        for pid, trajs in groups.items():
            if len(trajs) == self.k_samples and all(t.done for t in trajs):
                ready.append(trajs)
                for t in trajs:
                    self.active.pop(t.key, None)
                    self.completed.append(t)
        return ready

    def stats(self) -> dict[str, float]:
        """返回调度器统计信息。"""
        return {
            "iteration": float(self.iteration),
            "active": float(len(self.active)),
            "paused": float(len(self.paused)),
            "completed": float(len(self.completed)),
        }


def staleness_regularizer(
    logp_new: Tensor,
    logp_old: Tensor,
    *,
    epsilon: float = 0.2,
) -> Tensor:
    """Per-token 约束，将更新限制在局部邻域内。

    轨迹跨越多个迭代时数据可能任意陈旧，所以正则化器逐 token 作用，
    而非序列级 ratio——一个非常 off-policy 的 token 不会炸掉整个轨迹的更新。
    """
    ratio = (logp_new - logp_old).exp()
    return (ratio - 1.0).clamp(-epsilon, epsilon).abs().mean()


def clipped_policy_ratio(
    logp_new: Tensor, logp_old: Tensor, advantages: Tensor, *, epsilon: float = 0.2
) -> Tensor:
    """Per-token clipped surrogate objective (PPO 风格)。"""
    ratio = (logp_new - logp_old).exp()
    unclipped = ratio * advantages
    clipped = ratio.clamp(1 - epsilon, 1 + epsilon) * advantages
    return -torch.minimum(unclipped, clipped).mean()
